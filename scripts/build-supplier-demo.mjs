#!/usr/bin/env node
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const inputs = ['servers/supplier-statement-check/src/core.ts', 'billing/browser/supplier-demo.mjs', 'billing/browser/supplier-csv.mjs'];
const hash = createHash('sha256');
for (const file of inputs) { hash.update(file); hash.update(readFileSync(new URL(file, root))); }
const inputHash = hash.digest('hex');
const notices = [readFileSync(new URL('servers/supplier-statement-check/LICENSE', root), 'utf8'), readFileSync(new URL('node_modules/zod/LICENSE', root), 'utf8')].join('\n\nThird-party Zod license:\n');
const result = await build({ absWorkingDir: fileURLToPath(root), entryPoints: ['billing/browser/supplier-demo.mjs'], bundle: true, platform: 'browser', format: 'iife', target: ['es2022'], minify: true, write: false, legalComments: 'inline', banner: { js: '/*!\n' + notices + '\n*/' } });
const body = '// Generated by scripts/build-supplier-demo.mjs; actual engine and UI source hash below.\nexport const SUPPLIER_DEMO_INPUT_SHA256 = ' + JSON.stringify(inputHash) + ';\nexport const SUPPLIER_DEMO_JAVASCRIPT = ' + JSON.stringify(result.outputFiles[0].text) + ';\n';
const out = new URL('billing/src/supplier-demo-bundle.js', root);
if (process.argv.includes('--check')) { if (readFileSync(out, 'utf8') !== body) throw Error('Rebuild supplier statement demo'); }
else writeFileSync(out, body);
console.log('Browser supplier statement asset: ' + result.outputFiles[0].text.length + ' bytes');
